"""Export the final RCS catalogue, publication tables and inspectable fit curves.
Run after estimate.py, catalog.py, integrated_core.py, extra_candidates.py.
Input spectra were extracted on seid using extract.py; native archive untouched.
"""
from pathlib import Path
from datetime import datetime, timezone, timedelta
import shutil, hashlib
import h5py, numpy as np
from integrated_core import kernel
ROOT=Path(__file__).resolve().parents[2]
PAPER=ROOT/'arecibo_overleaf'

def clock(t,ast=False):
    return datetime.fromtimestamp(t,timezone(timedelta(hours=-4) if ast else timedelta())).strftime('%H:%M:%S')
def sci(x):
    a,b=f'{x:.2e}'.split('e');return rf'${float(a):.2f}\times10^{{{int(b)}}}$'
def table(rows,caption,label):
    text=[r'\begin{table}[p]',r'\centering',r'\caption{'+caption+'}',r'\label{'+label+'}',r'\small',r'\begin{tabular}{llrrrr}',r'\hline',r'UTC & AST & $f$ (MHz) & $z$ (km) & $\sigma_{\rm eq}$ (m$^2$) & dB m$^2$ \\',r'\hline']
    for t,f,z,s,db in rows:
        text.append(f'{clock(t)} & {clock(t,True)} & ${f:+.4f}$ & {z:.2f} & {sci(s)} & {db:.1f} '+r'\\')
    return '\n'.join(text+[r'\hline',r'\end{tabular}',r'\end{table}',''])

with h5py.File(ROOT/'data/plasma_line_rcs.h5','a') as h:
    cat=h['catalog/rows'][:];peaks=h['catalog/peak_summary'][:]
    assert cat.shape==(50,14) and np.all(np.isfinite(cat)) and np.all(cat[:,8]>0)
    assert np.allclose(10*np.log10(cat[:,8]),cat[:,9])
    assert np.all(h['ion_check/calibration_valid'][:][cat[:,1].astype(int)])
    for j in range(4):
        h[f'band{j}'].attrs['rcs_status']='Fixed44us detection-screen diagnostic. Final broadened spectral-area RCS is catalog/rows.'
    for s in peaks:
        j,i=int(s[0]),int(s[1]);g=h[f'band{j}'];idx=np.flatnonzero((cat[:,0]==j)&(cat[:,1]==i))[0]
        A,fc,sig,b,slope=h['catalog/core_width_window_fits'][idx,1,1:6]
        x=g['frequency_mhz'][:];xx=np.linspace(x.min(),x.max(),1001);origin=g['values'][i,1]
        yy=A*kernel(xx,fc,sig)+b+slope*(xx-origin)
        for name,a in [('peak_dense_frequency_mhz',xx),('peak_dense_fit',yy)]:
            if name in g:del g[name]
            g[name]=a
    h['catalog/rows'].attrs['columns']=h['catalog'].attrs['final_columns']
    h['catalog/rows'].attrs['time_zone']='UTC Unix seconds; AST=UTC-4 hours'
    h['catalog/rows'].attrs['status']='49 main-branch integrations and1 isolated opposite-sideband candidate; not50 independent sources.'
    h['provenance'].attrs['export_code']=Path(__file__).read_text()
    pkrows=[r[[2,3,4,6,7]] for r in peaks]
    pkrows += [r[[0,1,2,4,5]] for r in h['unclassified_narrow_features/rows'][:]]
    caption=('Largest equivalent cross section in each retained branch, followed by two unclassified lower-altitude narrow features. '
             'The negative 5.340 MHz row is an isolated opposite-sideband candidate. The last two rows are conditional estimates at apparent range; their plasma-wave origin and true range are unverified. All times are on 4 May 2018.')
    (PAPER/'rcs_peak_table.tex').write_text('% Generated by analysis/plasma_line_rcs/export.py.\n'+table(pkrows,caption,'tab:pl-rcs-peaks').replace('[p]','[htbp]'))
    appendix=r'''% Generated by analysis/plasma_line_rcs/export.py.
\section{Spectral fits and time-resolved RCS catalogue}
\label{app:rcs-catalogue}
The catalogue contains all 50 integrations retained by the stated selection
in the two persistent upper-layer frequency bands. It is not a count of
independent sources or a completeness claim across all frequencies and ranges.
The signed frequencies follow the original analysis convention.
The negative-frequency entry at 17:14:23 UTC is the isolated opposite-sideband
candidate discussed in Section~\ref{sec:rcs-results}.
The native spectral samples and broadened response fits at the three branch
maxima are shown in Figure~\ref{fig:pl-rcs-fits}.

\begin{figure}[htbp]
\centering
\includegraphics[width=0.9\textwidth,height=0.65\textheight,keepaspectratio]{figures/model/plasma_line_rcs_fits.pdf}
\caption{Native spectral samples at the strongest return in each retained
branch, with fitted broadened pulse responses and local backgrounds.
The third panel is the isolated opposite-sideband candidate.
The fitted area, after subtracting the matching opposite-sideband area,
is converted to equivalent RCS. The Gaussian broadening is descriptive;
it is not interpreted as an intrinsic thermal linewidth.}
\label{fig:pl-rcs-fits}
\end{figure}
\clearpage
'''
    cat=cat[np.argsort(cat[:,2])]
    for k in range(2):
        rows=[r[[2,3,4,8,9]] for r in cat[k*25:(k+1)*25]]
        appendix+=table(rows,f'Time-resolved equivalent RCS, part {k+1} of 2. All times are on 4 May 2018. Estimates use simultaneous ion-line calibration and the nominal antenna gain.','tab:rcs-catalogue-'+str(k+1))+'\n\\clearpage\n'
    (PAPER/'rcs_catalogue.tex').write_text(appendix)
    # Compact scientific deliverable: all estimates, source hashes, calibration,
    # native peak spectra and fitted curves, with no diagnostic amplitude maps.
    dest=PAPER/'data/plasma_line_rcs.h5'
    with h5py.File(dest,'w') as out:
        for key,value in h.attrs.items():out.attrs[key]=value
        for key in ['catalog','unclassified_narrow_features','ion_check','provenance','time_unix_s','es_peak_height_km','ipp_us','source_files','source_sha256']:h.copy(key,out)
        for s in peaks:
            j,i=int(s[0]),int(s[1]);g=h[f'band{j}'];og=out.create_group(f'peak_band{j}')
            og['frequency_mhz']=g['frequency_mhz'][:];og['native_spectrum']=g['observed'][i]
            og['fit_frequency_mhz']=g['peak_dense_frequency_mhz'][:];og['fit_spectrum']=g['peak_dense_fit'][:]
            og.attrs.update(time_unix_s=s[2],height_km=s[4],record_index=i)
    print('Exported',len(cat),'upper-layer estimates,',len(pkrows)-len(peaks),'unclassified lower-altitude candidates',dest.stat().st_size,'bytes')
with h5py.File(PAPER/'data/plasma_line_rcs.h5','a') as out:
    out.attrs['full_analysis_sha256']=hashlib.sha256((ROOT/'data/plasma_line_rcs.h5').read_bytes()).hexdigest()
# Retain calculation and figure provenance as source code, not figure annotations.
code=PAPER/'model_code/plasma_line_rcs';code.mkdir(exist_ok=True)
for p in Path(__file__).parent.glob('*.py'):shutil.copy2(p,code/p.name)
for p in [ROOT/'plotter/src/bin/plasma_line_rcs.rs',ROOT/'plotter/src/time_axes.rs']:
    shutil.copy2(p,code/p.name)
for name in ['plasma_line_rcs_time','plasma_line_rcs_fits']:
    shutil.copy2(ROOT/f'figures/{name}.pdf',PAPER/f'figures/model/{name}.pdf')
