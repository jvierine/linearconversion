"""Free-space-equivalent EIRP from the existing coherent radar angle scan.

Distances and incidence angles are independent scaling variables, not a
ray-traced source-location inversion. No additional propagation loss is applied.
"""
from pathlib import Path
import argparse
import hashlib
import h5py
import numpy as np


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument('--scan', type=Path, required=True)
    parser.add_argument('--h5', type=Path, required=True)
    parser.add_argument('--tex', type=Path, required=True)
    args = parser.parse_args()
    angles = np.array([0., 10., 14., 19.5, 25.])
    ranges = np.array([125., 250., 500.]) * 1000
    with h5py.File(args.scan) as src:
        theta = src['angle/degrees'][:] if 'angle' in src else src['angle_deg'][:]
        flux = src['angle/required_flux_W_m2'][:] if 'angle' in src else src['incident_vertical_flux_W_m2'][:]
        idx = [int(np.flatnonzero(np.isclose(theta, a, atol=1e-8, rtol=0))[0]) for a in angles]
        selected = flux[idx]
    eirp = 4*np.pi*selected[:, None]*ranges[None, :]**2/np.cos(np.deg2rad(angles[:, None]))
    assert 1.70 < eirp[2, 0] < 1.72
    assert np.allclose(eirp[:, 2]/eirp[:, 0], 16)
    args.h5.parent.mkdir(parents=True, exist_ok=True)
    with h5py.File(args.h5, 'w') as h:
        h['incidence_angle_deg'] = angles
        h['incident_vertical_flux_W_m2'] = selected
        h['slant_distance_m'] = ranges
        h['free_space_equivalent_EIRP_W'] = eirp
        h.attrs['definition'] = 'EIRP=4*pi*r^2*Fz/cos(theta); independent distance and angle scaling; no path-loss or focusing correction'
        h.attrs['scope'] = '5.34 MHz enhancement; optimized polarization at each angle; coherent beam filling; magnetic-meridian scan'
        h.attrs['scan_sha256'] = hashlib.sha256(args.scan.read_bytes()).hexdigest()
        h['provenance/source'] = Path(__file__).read_text()
    rows = [f"{a:g}"+r'$^\circ$ & '+ ' & '.join(f'{v:.2g}' for v in row)+r'\\' for a, row in zip(angles,eirp)]
    # Render scientific labels only; provenance stays in the LaTeX comment.
    text = r'''% Generated by model_code/illumination_power_scale.py; data/illumination_power_scale.h5.
\begin{table}[htbp]
\centering
\caption{Free-space-equivalent EIRP (W) sufficient to reproduce the
5.34 MHz enhancement under optimized polarization and coherent beam
filling. Columns give slant propagation distances, not horizontal ground
ranges. These are power-scaling examples, not inferred transmitter locations.}
\label{tab:illuminator-power}
\begin{tabular}{lrrr}
\hline
Incidence angle & 125 km & 250 km & 500 km\\
\hline
'''+ '\n'.join(rows) +r'''
\hline
\end{tabular}
\end{table}
'''
    # Scientific notation formatted explicitly in TeX.
    import re
    text = re.sub(r'([\d.]+)e\+0?(\d+)', lambda m: '$'+m[1]+r'\times10^{'+m[2]+'}$', text)
    args.tex.write_text(text)
    print(text)


if __name__ == '__main__':
    main()
